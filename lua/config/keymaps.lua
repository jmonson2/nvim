-- Keymaps are automatically loaded on the VeryLazy event
-- Default keymaps that are always set: https://github.com/LazyVim/LazyVim/blob/main/lua/lazyvim/config/keymaps.lua
-- Add any additional keymaps here
local dap = require("dap")
vim.keymap.set("n", "<M-b>", dap.toggle_breakpoint, {})
vim.keymap.set("n", "<M-c>", dap.continue, {})
vim.keymap.set("n", "<F5>", dap.continue, {})
vim.keymap.set("n", "<F10>", dap.step_over, {})
vim.keymap.set("n", "<F11>", dap.step_into, {})
vim.keymap.set("n", "<F12>", dap.step_out, {})
-- vim.keymap.set("n", "<M-lp>", dap.set_breakpoint(nil, nil, vim.fn.input("Log point message: ")), {})
vim.keymap.set("n", "<M-dr>", dap.repl.open, {})
vim.keymap.set("n", "<M-dl>", dap.run_last, {})
vim.keymap.set({ "n", "v" }, "<M-dh>", function()
  require("dap.ui.widgets").hover()
end)
vim.keymap.set({ "n", "v" }, "<M-dp>", function()
  require("dap.ui.widgets").preview()
end)
vim.keymap.set("n", "<M-df>", function()
  local widgets = require("dap.ui.widgets")
  widgets.centered_float(widgets.frames)
end)
vim.keymap.set("n", "<M-ds>", function()
  local widgets = require("dap.ui.widgets")
  widgets.centered_float(widgets.scopes)
end)
